'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {randomUUID} = require('node:crypto');
const {parseArgs} = require('node:util');
const {capture} = require('./lib/capture.cjs');
const {inTemp} = require('./lib/runner.cjs');

const help = `HollowImport  ·  private import failure → shareable Node repro

  hollow-import demo [--out repro.cjs]
  hollow-import capture PACKAGE[/SUBPATH] --from DIRECTORY [--out repro.cjs]
                        [--control PACKAGE/WORKING] [--condition NAME] [--clean]

From a source checkout, use node cli.cjs in place of hollow-import.
Set --from to the directory containing the file with the failing import.
A repro is saved only after the anonymous result matches the
observed failure and a working control. Output must be a new file.

Recipient: node repro.cjs                  replay the evidence
           node repro.cjs --inspect        inspect all case-specific data
           node repro.cjs --markdown       copy a report into a GitHub issue
           node repro.cjs --card proof.html  create an offline card with the repro inside
           node repro.cjs --unpack demo    write an editable native fixture`;

// Embedded into the standalone file; only refers to the runner's public data
// and its standard-library imports. It does not import the capture tool.
function standalone(capsule, argv) {
  validateCapsule(capsule);
  if (argv.length === 2 && argv[0] === '--card') {
    if (path.extname(argv[1]) !== '.html') throw new Error('Use a new .html filename.');
    replay(capsule, () => {});
    const html = makeCard(capsule, fs.readFileSync(__filename, 'utf8'));
    fs.writeFileSync(argv[1], html, {flag: 'wx'});
    console.log('Verified. The standalone repro is embedded in the offline HTML.');
    return;
  }
  if (argv.length === 1 && argv[0] === '--inspect') {
    console.log(JSON.stringify(capsule, null, 2));
    return;
  }
  if (argv.length === 1 && argv[0] === '--markdown') {
    replay(capsule, () => {});
    console.log('### Native Node resolution repro\n\nCapture: Node ' + capsule.node
      + '. Verified replay: Node ' + process.versions.node + '.\n');
    console.log('| Entry | Conditions | ESM import | CommonJS require |\n|---|---|---|---|');
    for (const row of capsule.rows) {
      const view = result => /^[A-Z_]+$/.test(result) ? result : 'OK → ' + result;
      console.log('| ' + [row.spec, row.condition || 'default', view(row.expected.import),
        view(row.expected.require)].join(' | ') + ' |');
    }
    console.log('\nIf you received an HTML report, download repro.cjs from it. Review the script, then run `node repro.cjs`.');
    return;
  }
  if (argv.length === 2 && argv[0] === '--unpack') {
    const dest = path.resolve(argv[1]);
    fs.mkdirSync(dest); // Refuse even an existing empty directory.
    materialize(dest, capsule);
    const row = capsule.rows.find(r => Object.values(r.expected).some(v => /^[A-Z_]+$/.test(v)));
    const esm = /^[A-Z_]+$/.test(row.expected.import);
    const file = esm ? 'run.mjs' : 'run.cjs';
    const code = esm ? 'await import(' : 'require.resolve(';
    fs.writeFileSync(path.join(dest, file), code + JSON.stringify(row.spec) + ');\n');
    console.log('In the new directory, trigger the native failure with:\n  node '
      + (row.condition ? '--conditions=' + row.condition + ' ' : '') + file);
    return;
  }
  if (argv.length) throw new Error('Use no arguments, --inspect, --markdown, --card NEW.html, or --unpack NEW_DIRECTORY.');
  console.log('HollowImport     clean native resolution  |  captured Node ' + capsule.node + '  |  replay Node ' + process.versions.node);
  replay(capsule);
  console.log('MATCH  all failures and successful target identities agree.');
}

function persist(capsule, destination) {
  const runner = fs.readFileSync(path.join(__dirname, 'lib', 'runner.cjs'), 'utf8');
  const {makeCard} = require('./lib/card.cjs');
  const license = fs.readFileSync(path.join(__dirname, 'LICENSE'), 'utf8');
  const body = '// Generated by HollowImport. Zero dependencies.\n/*\n' + license + '\n*/\n' + runner
    + '\n' + makeCard.toString() + '\nconst capsule = ' + JSON.stringify(capsule, null, 2) + ';\n'
    + 'try { (' + standalone.toString() + ')(capsule, process.argv.slice(2)); }\n'
    + 'catch (error) { console.error(error.message); process.exitCode = 1; }\n';
  const temp = path.join(path.dirname(destination), '.hollow-' + randomUUID() + '.tmp');
  fs.writeFileSync(temp, body, {flag: 'wx'});
  try { fs.linkSync(temp, destination); } finally { fs.unlinkSync(temp); }
  for (const row of capsule.rows) {
    for (const mode of ['import', 'require'])
      console.log('  ' + mode.padEnd(8) + row.spec.padEnd(22) + (row.condition || 'default').padEnd(15)
        + row.expected[mode]);
  }
  console.log('\nVERIFIED  ' + capsule.rows.length * 2 + ' observations matched a fresh synthetic package.');
  console.log('SHARE     ' + path.basename(destination) + '  (' + Buffer.byteLength(body) + ' bytes, no dependencies)');
}

function main() {
  const {values, positionals} = parseArgs({allowPositionals: true, options: {
    from: {type: 'string'}, out: {type: 'string'}, control: {type: 'string'},
    condition: {type: 'string'}, clean: {type: 'boolean'}, help: {type: 'boolean', short: 'h'}
  }});
  if (values.help || !positionals.length) { console.log(help); return; }
  if (typeof require('node:module').registerHooks !== 'function') throw new Error('Node 22.15+ is required.');
  const [command, spec] = positionals;
  const out = path.resolve(values.out || 'repro.cjs');
  if (path.extname(out) !== '.cjs') throw new Error('Use a .cjs output filename.');
  if (fs.existsSync(out)) throw new Error('Output already exists. Choose a new .cjs path.');
  if (command === 'capture' && spec && positionals.length === 2) {
    persist(capture(spec, {...values, from: values.from || process.cwd()}), out);
  } else if (command === 'demo' && positionals.length === 1 && !values.from && !values.condition && !values.control) {
    inTemp(root => {
      const name = '@private/example-engine';
      const pkg = path.join(root, 'node_modules', name);
      fs.mkdirSync(pkg, {recursive: true});
      fs.writeFileSync(path.join(pkg, 'package.json'), JSON.stringify({name, exports: {
        './private-client': {import: './missing-in-build.mjs', require: './secret-implementation.cjs'}
      }}));
      fs.writeFileSync(path.join(pkg, 'secret-implementation.cjs'), 'throw Error("Never execute business code");');
      persist(capture(name + '/private-client', {from: root, clean: true}), out);
    });
  } else throw new Error(help);
}

try { main(); } catch (error) {
  // OS/JSON parser exceptions can contain private absolute paths or excerpts.
  console.error((error.code || error instanceof SyntaxError) ? 'Capture stopped: ' + (error.code || 'invalid JSON')
    : error.message);
  process.exitCode = 1;
}
